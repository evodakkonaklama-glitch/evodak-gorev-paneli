const listeners = new Set();
let current = (() => {
  try {
    const saved = localStorage.getItem('evodak.lang');
    if (saved === 'tr' || saved === 'en') return saved;
  } catch { /* depolama kapalı olabilir */ }
  return 'tr'; // varsayılan dil Türkçe
})();
document.documentElement.lang = current;

export function getLang() { return current; }

export function setLang(lang) {
  if (lang !== 'tr' && lang !== 'en' || lang === current) return;
  current = lang;
  document.documentElement.lang = lang;
  try { localStorage.setItem('evodak.lang', lang); } catch { /* yok say */ }
  listeners.forEach((fn) => fn(lang));
}

export function onLangChange(fn) { listeners.add(fn); return () => listeners.delete(fn); }

export function t(key, params = {}) {
  const s = dict[current][key] ?? dict.tr[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (params[k] ?? ''));
}

export function hasKey(key) { return key in dict.tr; }
